bootstrap_dir="${1:?usage: grafana-cloud-setup.sh <bootstrap-dir> <grafana-dir>}"
grafana_dir="${2:?usage: grafana-cloud-setup.sh <bootstrap-dir> <grafana-dir>}"
tfvars="${bootstrap_dir}/terraform.tfvars"
grafana_tfvars="${grafana_dir}/terraform.tfvars"

# The wizard keeps nothing in a .env file: the stack URL and external ID go to
# terraform.tfvars files and each token straight to Secrets Manager, so no saved value is
# offered back on a re-run.
ENV_FILE=/dev/null

# is_stack_url VALUE succeeds for a Grafana Cloud stack URL, with or without a trailing
# slash.
# shellcheck disable=SC2317,SC2329 # called by name through ask_valid
is_stack_url() { [[ "$1" =~ ^https://[a-z0-9-]+\.grafana\.net/?$ ]]; }

# The external ID and email checks are shared with bootstrap.sh.
# Parameter expansion, not dirname, so the file is found even before the tool check below
# confirms the PATH.
# shellcheck source=scripts/bootstrap-values.sh
source "${BASH_SOURCE[0]%/*}/bootstrap-values.sh"

# ask_valid KEY PROMPT CHECK MESSAGE asks for KEY until CHECK accepts it, warning MESSAGE
# after each rejected answer.
ask_valid() {
  local key="$1" prompt="$2" check="$3" message="$4"
  while true; do
    if ! ask "${key}" "${prompt}"; then
      echo "stdin closed before ${key} was entered; rerun the wizard" >&2
      return 1
    fi
    "${check}" "${!key}" && return 0
    warn "${message}"
  done
}

# read_output NAME prints the bootstrap output NAME, failing when the read fails or
# resolves to nothing rather than passing whatever terraform printed through as a value.
read_output() {
  local value
  if ! value="$(terraform -chdir="${bootstrap_dir}" output -raw "$1")" || [[ -z "${value}" ]]; then
    echo "cannot read bootstrap output $1; apply the bootstrap stack and rerun" >&2
    return 1
  fi
  printf '%s' "${value}"
}

# write_tfvar FILE KEY VALUE upserts KEY = "VALUE" into the terraform.tfvars FILE, keeping
# every other line. Creates the file at mode 0600; VALUE is validated by the caller, so it
# needs no HCL escaping.
write_tfvar() {
  local file="$1" key="$2" value="$3" tmp rc=0
  [[ -e "${file}" ]] || (umask 077 && : >"${file}")
  # The new file is built beside FILE and moved over it, so a failed write leaves the
  # old file whole.
  tmp=$(mktemp "${file}.XXXXXX")
  # grep exits 1 when no other line is left, which is fine; above 1 it could not read the
  # file, and writing on would replace every value in it with KEY alone.
  grep -vE "^${key}[[:space:]]*=" "${file}" >"${tmp}" || rc=$?
  if ((rc > 1)); then
    rm -f "${tmp}"
    echo "cannot read ${file}; check its permissions and rerun the wizard" >&2
    return 1
  fi
  printf '%s = "%s"\n' "${key}" "${value}" >>"${tmp}"
  mv -f "${tmp}" "${file}"
  printf '  %s✓ wrote%s %s → %s\n' "$GREEN" "$RESET" "${key}" "${file}"
}

# put_token SECRET_ID PROMPT asks for a token with hidden entry, again while it is empty,
# and writes it to SECRET_ID through aws's stdin.
put_token() {
  # Local, so the token is gone once the function returns; ask_secret still fills it
  # through bash's dynamic scope.
  local secret_id="$1" prompt="$2" TOKEN=""
  while [[ -z "${TOKEN}" ]]; do
    if ! ask_secret TOKEN "${prompt}"; then
      echo "stdin closed before the token for ${secret_id} was entered; rerun the wizard" >&2
      return 1
    fi
    [[ -n "${TOKEN}" ]] || warn "token is empty; paste it again"
  done
  if ! printf '%s' "${TOKEN}" | aws secretsmanager put-secret-value --region "${region}" \
    --secret-id "${secret_id}" --secret-string file:///dev/stdin >/dev/null; then
    echo "writing ${secret_id} failed; check the AWS identity can write it (aws's error is above) and rerun the wizard" >&2
    return 1
  fi
  printf '  %s✓ wrote%s token → Secrets Manager %s\n' "$GREEN" "$RESET" "${secret_id}"
}

# check_secret_set SECRET_ID fails unless the secret holds a non-empty value, reading only
# its length so the value itself is never printed.
check_secret_set() {
  local length
  if ! length="$(aws secretsmanager get-secret-value --region "${region}" --secret-id "$1" \
    --query 'length(SecretString)' --output text)"; then
    echo "cannot read $1 from Secrets Manager; check the AWS identity can read it and rerun the wizard" >&2
    return 1
  fi
  if [[ ! "${length}" =~ ^[0-9]+$ ]] || ((length == 0)); then
    echo "$1 holds no value; rerun the wizard" >&2
    return 1
  fi
  printf '  %s✓%s %s holds a value\n' "$GREEN" "$RESET" "$1"
}

run_wizard() {

  TOTAL_STAGES=8

  # Everything the stages need is checked before the operator starts the browser work.
  if [[ ! -d "${bootstrap_dir}" ]]; then
    echo "bootstrap dir ${bootstrap_dir} not found; pass the terraform/bootstrap directory" >&2
    exit 1
  fi
  if [[ ! -d "${grafana_dir}" ]]; then
    echo "grafana dir ${grafana_dir} not found; pass the terraform/grafana directory" >&2
    exit 1
  fi
  local tool
  for tool in terraform aws; do
    if ! command -v "${tool}" >/dev/null; then
      echo "${tool} not found on PATH; install it and rerun the wizard" >&2
      exit 1
    fi
  done
  if ! aws sts get-caller-identity >/dev/null; then
    echo "aws is not authenticated: set AWS_PROFILE to the bootstrap account and log in" >&2
    exit 1
  fi
  # With AWS CLI history on, aws records each call's parameters, the token included, in
  # ~/.aws/cli/history. `configure get` exits 1 when the setting is unset.
  if [[ "$(aws configure get cli_history || true)" == enabled ]]; then
    echo "cli_history is enabled in the AWS config, so aws would record each token; disable it and rerun the wizard" >&2
    exit 1
  fi

  banner "Grafana Cloud setup"

  stage "Grafana Cloud: free stack"
  say "Grafana Cloud's free tier holds the dashboards, metrics and traces (ADR-0026)."
  open_url "https://grafana.com/auth/sign-up/create-user"
  step "Sign up, or sign in, and create a stack on the Free plan in an EU region."
  step "Open the stack: its URL looks like https://<stack>.grafana.net."
  pause "Press Enter once the stack exists."
  ask_valid STACK_URL "Paste the stack URL (https://<stack>.grafana.net):" is_stack_url \
    "not a https://<stack>.grafana.net URL"
  STACK_URL="${STACK_URL%/}"

  stage "Grafana Assume Role: external ID"
  say "The bootstrap stack's IAM role trusts Grafana's AWS account only with this ID."
  open_url "${STACK_URL}/connections/datasources/new"
  step "Pick Amazon CloudWatch."
  step "Under Connection Details, set Authentication Provider to Grafana Assume Role."
  step "The instructions box shows Grafana's account ID and your External ID."
  note "The role trusts account 008923505280. If the box shows another account, set"
  note "grafana_account_id in ${tfvars} to it before the apply."
  ask_valid GRAFANA_EXTERNAL_ID "Paste the External ID:" is_external_id \
    "not a valid external ID; copy it from the instructions box"
  write_tfvar "${tfvars}" grafana_external_id "${GRAFANA_EXTERNAL_ID}"
  step "Back on that page, click Delete at the bottom, and Delete again to confirm."
  note "Picking the type created the data source; \`just grafana-up\` creates its own"
  note "CloudWatch data source with the role ARN, and two of the same name would clash."

  stage "Bootstrap: operator email"
  say "The bootstrap stack's spend-leak alarms page this address (ADR-0025)."
  if [[ -n "${TF_VAR_operator_email:-}" ]] || grep -qE '^operator_email[[:space:]]*=' "${tfvars}" 2>/dev/null; then
    note "operator_email is already set; the apply uses it."
  else
    ask_valid OPERATOR_EMAIL "Email address for spend-leak alerts:" is_email \
      "not an email address, or holds one of \" \\ \$ %"
    write_tfvar "${tfvars}" operator_email "${OPERATOR_EMAIL}"
    note "AWS emails a confirmation link on apply; click it, or no alert is delivered."
  fi

  stage "Bootstrap: apply"
  say "Applying the bootstrap stack creates the three empty secrets and the IAM role."
  if ! confirm "Plan and apply ${bootstrap_dir} now? Terraform asks again before it changes anything."; then
    echo "bootstrap not applied; rerun the wizard when ready" >&2
    exit 1
  fi
  terraform -chdir="${bootstrap_dir}" init -input=false
  terraform -chdir="${bootstrap_dir}" apply
  region="$(read_output region)"
  write_secret="$(read_output grafana_cloud_write_secret_name)"
  api_secret="$(read_output grafana_cloud_api_secret_name)"
  stack_read_secret="$(read_output grafana_cloud_stack_read_secret_name)"

  stage "Write token: metrics and traces"
  say "One access-policy token lets Prometheus and the Collector write to the stack."
  open_url "${STACK_URL}/a/grafana-auth-app"
  step "Click Create access policy; name it slipstream-write."
  step "Tick Write for metrics and traces only; a policy made here covers this stack alone."
  step "Click Create, then Add token on the new policy, and copy the token (glc_...)."
  note "Grafana shows the token once. It goes to ${write_secret}, not to any file."
  put_token "${write_secret}" "Paste the write token:"

  stage "API token: Grafana Terraform provider"
  say "A service account token lets the terraform/grafana stack manage data sources and dashboards."
  open_url "${STACK_URL}/org/serviceaccounts"
  step "Click Add service account; name it slipstream-terraform, role Admin."
  note "Admin, because creating the CloudWatch data source needs it; Editor cannot."
  note "If slipstream-terraform already exists, change its role to Admin and reuse it."
  step "Click Add service account token, generate it, and copy the token (glsa_...)."
  note "Grafana shows the token once. It goes to ${api_secret}, not to any file."
  put_token "${api_secret}" "Paste the API token:"

  stage "Stack-read token: public send endpoints"
  say "A Cloud API token lets the terraform/grafana stack read where Prometheus and the"
  say "Collector send: the hosted data sources name Grafana's internal hosts instead."
  open_url "https://grafana.com/profile/org"
  step "In the Cloud Portal, open Security, then Access Policies."
  step "Click Create access policy; name it slipstream-stack-read, realm this stack."
  step "Tick Read for stacks (stacks:read) only, and click Create."
  note "stacks:read is offered only here, not on the stack's own access policy page."
  step "Click Add token on the new policy, and copy the token (glc_...)."
  note "Grafana shows the token once. It goes to ${stack_read_secret}, not to any file."
  put_token "${stack_read_secret}" "Paste the stack-read token:"

  stage "Secrets: check"
  check_secret_set "${write_secret}"
  check_secret_set "${api_secret}"
  check_secret_set "${stack_read_secret}"
  # Written once every token is stored, so the URL never names a stack the stored tokens
  # do not belong to.
  write_tfvar "${grafana_tfvars}" grafana_url "${STACK_URL}"
  say "Next: \`just grafana-up\` creates the CloudWatch data source."
  pause "Press Enter to finish."

  finish
}

run_wizard "$@"
exit
