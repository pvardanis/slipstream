"""Render the serving fleet's manifest from the bench Engine's template (ADR-0031).

The serving fleet runs the same pod spec as the bench Engine (``k8s/vllm-gpu.yaml``), so
its manifest is generated from that template rather than copied by hand. The render fixes
the engine knobs at the 0%-share knob-sweep winner, ``32 fp8 off``, through the same
:func:`render_gpu_manifest` the flows use, then gives the fleet its own name, labels and
``serving`` namespace, drops ``replicas`` so an Argo CD sync never resets the count KEDA
alone owns, and makes its Service ClusterIP: outside traffic reaches the fleet only
through its proxy (``k8s/serving/serving-proxy.yaml``), whose request rate wakes it from
zero. The template's Namespace document is dropped: the workloads AppProject allows no
cluster-scoped resources, so the ``serving`` namespace is created outside this manifest.
"""

from typing import Any

import yaml

from slipstream_bench.orchestration.cluster import render_gpu_manifest
from slipstream_bench.orchestration.grid import EngineArgs, get_kv_engine_token

# The 0%-share knob-sweep winner, `32 fp8 off` (ADR-0009, ADR-0031): the share with the
# lowest concurrency ceiling, so the autoscaler's threshold is set against the most
# conservative config. The KV pool stays uncapped, as the sweep measured it.
SERVING_ENGINE_ARGS = EngineArgs(
    max_num_seqs=32,
    kv_engine_token=get_kv_engine_token("fp8"),
    prefix_caching_flag="--no-enable-prefix-caching",
    kv_cache_memory_bytes=None,
)

_SERVING_NAMESPACE = "serving"
_SERVING_NAME = "vllm-serving"
_SERVING_LABELS = {"app": _SERVING_NAME}

# Opens the committed manifest: the file is an output, so a reader edits the template
# and re-renders rather than editing it. A drift test holds it to a fresh render.
_HEADER = f"""\
# Generated by `just render-serving-manifest` from k8s/vllm-gpu.yaml: do not edit.
# The serving fleet (ADR-0031), at the 0%-share knob-sweep winner:
#   --max-num-seqs {SERVING_ENGINE_ARGS.max_num_seqs} \
--kv-cache-dtype {SERVING_ENGINE_ARGS.kv_engine_token} {SERVING_ENGINE_ARGS.prefix_caching_flag}
# Namespace {_SERVING_NAMESPACE}, a ClusterIP Service behind the serving proxy, and no replicas:
# KEDA alone owns the count.
"""


def render_serving_manifest(template_text: str) -> str:
    """Render the serving fleet's manifest from the bench Engine's template.

    :param template_text: the raw ``k8s/vllm-gpu.yaml`` text with its placeholders.
    :return: the serving fleet's manifest.
    :raise ValueError: when the template holds anything besides its Namespace, one
        Deployment and one Service.
    """
    rendered = render_gpu_manifest(
        template_text, engine_args=SERVING_ENGINE_ARGS, kv_cache_offload=False
    )
    documents = [
        doc for doc in yaml.safe_load_all(rendered) if doc["kind"] != "Namespace"
    ]
    kinds = sorted(doc["kind"] for doc in documents)
    if kinds != ["Deployment", "Service"]:
        raise ValueError(
            f"the serving fleet's manifest takes one Deployment and one Service from "
            f"the bench Engine's template besides its Namespace, but the template "
            f"holds {kinds}: only those two get the fleet's selectors, so give any "
            f"other resource its own place in the serving manifest"
        )
    for document in documents:
        _assign_serving_identity(document)
    return _HEADER + yaml.safe_dump_all(documents, sort_keys=False)


def _assign_serving_identity(document: dict[str, Any]) -> None:
    """Give one of the template's documents the serving fleet's identity, in place."""
    metadata = document["metadata"]
    metadata.update(name=_SERVING_NAME, namespace=_SERVING_NAMESPACE)
    metadata["labels"] = dict(_SERVING_LABELS)
    spec = document["spec"]
    if document["kind"] == "Deployment":
        del spec["replicas"]
        spec["selector"] = {"matchLabels": dict(_SERVING_LABELS)}
        spec["template"]["metadata"]["labels"] = dict(_SERVING_LABELS)
    elif document["kind"] == "Service":
        spec["selector"] = dict(_SERVING_LABELS)
        spec["type"] = "ClusterIP"
        for port in spec["ports"]:
            port.pop("nodePort", None)
